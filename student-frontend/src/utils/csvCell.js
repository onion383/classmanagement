// =========================================================================
// csvCell.js —— CSV 单元格转义（含公式注入防护）
//
// 只做转义还不够：Excel/WPS 会把以 = + - @ 开头的单元格当公式执行，
// 学生姓名这类完全由用户输入的内容写进 CSV 后，别人打开就可能被执行
// （=HYPERLINK(...)、=cmd|'...'!A1 这类老套路）。
// 标准做法（OWASP CSV Injection）是在这些值前面加一个单引号，让它保持文本。
//
// 制表符/回车开头也要处理：它们会让部分表格软件把后续内容当成新单元格或新行。
// =========================================================================

// Excel 的「公式起始字符」；纯数字的负数（-5）也会被加上前缀，这是可接受的代价。
// 1) 前导空白后再跟公式字符：` =cmd|...`、`\t=HYPERLINK(...)` 在 Excel/WPS 里仍会按公式求值；
// 2) 制表符/回车本身也要处理：它们会让部分表格软件把后续内容当成新单元格或新行。
const FORMULA_START = /^(?:[\t\r]|\s*[=+\-@])/

// 单个 CSV 单元格：先防公式注入，再按需加引号（含逗号/引号/换行时）
export function csvCell(value) {
  let text = value === undefined || value === null ? '' : String(value)
  if (FORMULA_START.test(text)) text = "'" + text
  if (/[",\n\r]/.test(text)) return '"' + text.replace(/"/g, '""') + '"'
  return text
}
